// Seed all 300 practice DM questions from preview-dm.json into
// decision_making_questions (and child tables), with fresh UUIDs,
// random order, and pre-baked venn geometry.
//
// Usage:
//   node scripts/generate-dm-practice-seed.mjs > supabase/migrations/20260422000001_seed_dm_practice_questions.sql

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { findOptimalLayoutWidth } from '../src/utils/venn/layout.js';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(__filename), '..');
const BAKE_WIDTH_PX = 340;

const raw = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/dev/preview-dm.json'), 'utf8'));
const questions = Array.isArray(raw) ? raw : (raw.questions || []);

function bake(vennConfig) {
  return findOptimalLayoutWidth(vennConfig, {
    maxWidthPx: BAKE_WIDTH_PX,
    minHeightPx: 160,
  });
}

function sqlStr(s) {
  if (s == null) return 'NULL';
  return `'${String(s).replace(/'/g, "''")}'`;
}

function sqlJson(obj) {
  if (obj == null) return 'NULL';
  return `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
}

// Fisher-Yates shuffle
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

const shuffled = shuffle(questions);

const lines = [];
lines.push('-- Auto-generated by scripts/generate-dm-practice-seed.mjs');
lines.push(`-- Bake width: ${BAKE_WIDTH_PX}px  |  Questions: ${shuffled.length}`);
lines.push('-- DO NOT EDIT — re-run the script to regenerate.\n');
lines.push('DO $$');
lines.push('DECLARE');
lines.push('  v_id UUID;');
lines.push('BEGIN\n');

for (let i = 0; i < shuffled.length; i++) {
  const q = shuffled[i];
  const orderIndex = i + 1;
  const uuid = crypto.randomUUID();

  // Bake stimulus venn geometry if applicable
  let stimulusGeo = null;
  if (q.type === 'venn_diagram' && q.stimulus_diagram) {
    try {
      stimulusGeo = bake(q.stimulus_diagram);
    } catch (err) {
      process.stderr.write(`WARN: ${q.id} stimulus bake failed: ${err.message}\n`);
    }
  }

  lines.push(`  -- [${orderIndex}] ${q.title}`);
  lines.push(`  INSERT INTO decision_making_questions`);
  lines.push(`    (id, title, type, stem, table_data, stimulus_diagram, correct_answer, answer_reason, order_index, difficulty, venn_geometry)`);
  lines.push(`  VALUES (`);
  lines.push(`    '${uuid}',`);
  lines.push(`    ${sqlStr(q.title)},`);
  lines.push(`    '${q.type}'::dm_question_type,`);
  lines.push(`    ${sqlStr(q.stem)},`);
  lines.push(`    ${sqlJson(q.table_data)},`);
  lines.push(`    ${sqlJson(q.stimulus_diagram)},`);
  lines.push(`    ${sqlStr(q.correct_answer)},`);
  lines.push(`    ${sqlStr(q.answer_reason)},`);
  lines.push(`    ${orderIndex},`);
  lines.push(`    '${q.difficulty || 'normal'}',`);
  lines.push(`    ${sqlJson(stimulusGeo)}`);
  lines.push(`  ) RETURNING id INTO v_id;\n`);

  // Options (logic_puzzle, venn_diagram, probabilistic, recognising_assumptions)
  const opts = q.decision_making_question_options || [];
  if (opts.length > 0) {
    for (const opt of opts) {
      let optGeo = null;
      if (opt.option_data) {
        try {
          optGeo = bake(opt.option_data);
        } catch (err) {
          process.stderr.write(`WARN: ${q.id} option ${opt.label} bake failed: ${err.message}\n`);
        }
      }
      lines.push(`  INSERT INTO decision_making_question_options`);
      lines.push(`    (question_id, label, option_text, option_data, order_index, venn_geometry)`);
      lines.push(`  VALUES (`);
      lines.push(`    v_id, '${opt.label}', ${sqlStr(opt.option_text)}, ${sqlJson(opt.option_data)}, ${opt.order_index}, ${sqlJson(optGeo)}`);
      lines.push(`  );`);
    }
    lines.push('');
  }

  // Statements (syllogism, interpreting_info)
  const stmts = q.decision_making_question_statements || [];
  if (stmts.length > 0) {
    for (const st of stmts) {
      lines.push(`  INSERT INTO decision_making_question_statements`);
      lines.push(`    (question_id, statement_text, correct_answer, order_index)`);
      lines.push(`  VALUES (`);
      lines.push(`    v_id, ${sqlStr(st.statement_text)}, ${sqlStr(st.correct_answer)}, ${st.order_index}`);
      lines.push(`  );`);
    }
    lines.push('');
  }
}

lines.push('END $$;');

process.stdout.write(lines.join('\n') + '\n');
process.stderr.write(`Done. ${shuffled.length} questions processed.\n`);

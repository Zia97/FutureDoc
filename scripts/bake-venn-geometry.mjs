// Bake venn geometry for timed DM tests 1 and 2.
// Reads preview-dm.json (which mirrors exactly what was seeded into the DB),
// runs findOptimalLayoutWidth on each vennConfig at BAKE_WIDTH_PX,
// and writes a SQL migration to stdout.
//
// Usage:
//   node scripts/bake-venn-geometry.mjs > supabase/migrations/20260421000003_bake_venn_geometry.sql

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findOptimalLayoutWidth } from '../src/utils/venn/layout.js';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(__filename), '..');
const BAKE_WIDTH_PX = 340;

const data = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'src/dev/preview-dm.json'), 'utf8'),
);

// Parse 'dm1r-023-venn' → { testId: 1, orderIndex: 23 }
function parseId(id) {
  const m = id.match(/^dm(\d+)r-(\d+)/);
  if (!m) throw new Error(`Cannot parse question id: ${id}`);
  return { testId: parseInt(m[1], 10), orderIndex: parseInt(m[2], 10) };
}

function bake(vennConfig) {
  return findOptimalLayoutWidth(vennConfig, {
    maxWidthPx: BAKE_WIDTH_PX,
    minHeightPx: 160,
  });
}

function sqlJson(obj) {
  // Single-quote the JSON string so it is safe inside a DO $$ block.
  return `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
}

const lines = [];

lines.push('-- Auto-generated by scripts/bake-venn-geometry.mjs');
lines.push(`-- Bake width: ${BAKE_WIDTH_PX}px`);
lines.push('-- DO NOT EDIT — re-run the bake script to regenerate.\n');
lines.push('DO $$');
lines.push('BEGIN\n');

for (const q of data) {
  if (q.type !== 'venn_diagram') continue;

  const { testId, orderIndex } = parseId(q.id);

  if (q.stimulus_diagram) {
    // INTERPRET question — bake stimulus, store on the question row
    let geo;
    try {
      geo = bake(q.stimulus_diagram);
    } catch (err) {
      process.stderr.write(`WARN: ${q.id} stimulus bake failed: ${err.message}\n`);
      continue;
    }
    lines.push(`  -- ${q.title} (test ${testId}, Q${orderIndex}) — stimulus`);
    lines.push(`  UPDATE timed_decision_making_questions`);
    lines.push(`    SET venn_geometry = ${sqlJson(geo)}`);
    lines.push(`    WHERE test_id = ${testId} AND order_index = ${orderIndex};\n`);
  } else {
    // SELECT question — bake each option, store on the option row
    const opts = q.decision_making_question_options || [];
    for (const opt of opts) {
      if (!opt.option_data) continue;
      let geo;
      try {
        geo = bake(opt.option_data);
      } catch (err) {
        process.stderr.write(`WARN: ${q.id} option ${opt.label} bake failed: ${err.message}\n`);
        continue;
      }
      lines.push(`  -- ${q.title} (test ${testId}, Q${orderIndex}) — option ${opt.label}`);
      lines.push(`  UPDATE timed_decision_making_question_options`);
      lines.push(`    SET venn_geometry = ${sqlJson(geo)}`);
      lines.push(`    WHERE label = '${opt.label}'`);
      lines.push(`      AND question_id = (`);
      lines.push(`        SELECT id FROM timed_decision_making_questions`);
      lines.push(`        WHERE test_id = ${testId} AND order_index = ${orderIndex}`);
      lines.push(`      );\n`);
    }
  }
}

lines.push('END $$;');

process.stdout.write(lines.join('\n') + '\n');
process.stderr.write('Done.\n');
